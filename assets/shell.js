/* =========================================================================
   multipage · shell.js   (vanilla, no build)

   The SHARED CHROME for every page: app bar, cross-page nav, footer and the
   detail <dialog>. It also owns global state (language + theme) and exposes a
   tiny toolkit on window.LDW that each page's app.js reuses.

   Loaded on EVERY page BEFORE app.js. It:
     1. derives the language from <html lang> (each URL IS one language:
        root = en, the zh-Hant/ subdirectory mirrors every page in Chinese —
        twin files generated by scripts/build_i18n.py) and reads the
        persisted theme (localStorage),
     2. injects app bar + nav + footer + dialog around <main id="page">,
     3. renders the language link (a real <a> to this page's twin URL) and
        wires the theme toggle,
     4. highlights the current page (from <body data-page="...">),
     5. nav links are same-directory siblings, so they stay inside the
        current language tree by construction.

   Cross-page language persistence is structural: the language lives in the
   URL, so following any in-language link keeps it. Theme persists via
   localStorage (an origin-wide store).
   ========================================================================= */
(function () {
  "use strict";

  var META = window.SITE_META || { title: {}, subtitle: {}, footer: {} };
  var PAGES = Array.isArray(window.SITE_PAGES) ? window.SITE_PAGES : [];

  /* ---------- chrome i18n (page content strings live in the data) ---------- */
  /* 語言是固定的(一個 URL 一個語言),所以這裡不能出現「Close / 關閉」這種把
     兩個語言擠在同一個字串裡的寫法 —— 讀屏會把斜線跟另一個語言一起念出來。
     每個 key 兩個語言各一份,`ui()` 照 <html lang> 取。 */
  var I18N = {
    en: {
      close: "Close", menu: "Pages", skip: "Skip to content",
      theme: "Switch between dark and light theme",
      homeLink: "peteraim.com (opens in a new tab)",
      linkedin: "LinkedIn (opens in a new tab)",
      sortBy: "Sort by {label}",
      barChart: "Bar chart", lineChart: "Line chart",
      contents: "Contents", map: "Map", yes: "Yes", no: "No",
      switchLang: "Switch to Traditional Chinese",
      emptyQ: "Nothing matches \u201c{q}\u201d.",
      emptyFilters: "Nothing matches the current filters.",
      emptyBoth: "Nothing matches \u201c{q}\u201d under the current filters.",
      emptyHint: "Try a shorter word \u2014 search covers repository names, the notes and GitHub topics, in both languages.",
      emptyClear: "Clear search and filters"
    },
    zh: {
      close: "關閉", menu: "頁面", skip: "跳到內容",
      theme: "切換深色與淺色主題",
      homeLink: "peteraim.com(在新分頁開啟)",
      linkedin: "LinkedIn(在新分頁開啟)",
      sortBy: "依「{label}」排序",
      barChart: "長條圖", lineChart: "折線圖",
      contents: "目錄", map: "地圖", yes: "有", no: "沒有",
      switchLang: "切換到英文版",
      emptyQ: "沒有符合「{q}」的項目。",
      emptyFilters: "沒有符合目前篩選條件的項目。",
      emptyBoth: "在目前的篩選條件下,沒有符合「{q}」的項目。",
      emptyHint: "換個更短的關鍵字試試 —— 搜尋會比對 repo 名稱、說明與 GitHub topics,而且中英文一起搜。",
      emptyClear: "清除搜尋與篩選"
    }
  };

  /* ---------- sandbox-safe localStorage ---------- */
  function lsGet(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function lsSet(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } }

  /* ---------- GitHub 星數快取 ----------
     未帶 token 的 api.github.com 限流是**每個 IP 每小時 60 次**。這個站有 11 個
     根層頁面 × 2 個語言,而導覽是實體連結(每次換頁都是完整載入),原本每一次
     載入都無條件打一次 —— 一個訪客逛十幾頁就吃掉四分之一額度,而同一個出口 IP
     後面的人共用這個額度。被限流的人看到的星數永遠是「—」。

     所以:成功的結果快取一小時,失敗(含 403 限流)退避十分鐘不重試。
     星數這種東西不需要更即時。 */
  var STAR_TTL = 3600e3;        // 成功後 1 小時內直接用快取
  var STAR_BACKOFF = 600e3;     // 失敗後 10 分鐘內不再試

  function starKey(repo) { return "stars:" + repo; }
  function starRead(repo) {
    try {
      var raw = lsGet(starKey(repo));
      if (!raw) return null;
      var o = JSON.parse(raw);
      return (o && typeof o.at === "number") ? o : null;
    } catch (e) { return null; }   // 壞掉的 JSON 當成沒有快取
  }
  function starWrite(repo, o) {
    o.at = Date.now();
    try { lsSet(starKey(repo), JSON.stringify(o)); } catch (e) { /* ignore */ }
  }
  function starFmt(n) {
    return n >= 1000 ? (n / 1000).toFixed(1).replace(/\.0$/, "") + "k" : String(n);
  }

  /* ---------- global state ---------- */
  /* 語言由 URL 決定:root 是英文、zh-Hant/ 子目錄是中文鏡射,
     每份靜態檔的 <html lang> 就是它的語言 —— 不存 localStorage、不切換。 */
  var state = {
    lang:  (document.documentElement.lang || "en").toLowerCase().indexOf("zh") === 0 ? "zh" : "en",
    /* 預設深色 —— 首頁那套「可篩選的場」是深色原生的設計,淺色是備選 */
    theme: lsGet("theme") || "dark"
  };

  /* 這一頁的 <title> 是不是靜態檔自己帶的。
     每個頁面的 <title> 都是手寫的(英文頁直接寫、中文雙生頁由 build_i18n.py
     換上 data-zh),裡面有該頁專屬的說明與總數,而且**沒有任何腳本會重產它**。
     所以 shell 不去覆蓋 —— 只有頁面根本沒給 <title> 時才組一個備援。
     覆蓋掉的後果是首頁把兩個同義的名字串在一起:SITE_META.title 是站名、
     首頁的 page.title 也是站名,中文版就變成「Peter 的 GitHub 收藏 ·
     Peter 的 GitHub 收藏」。而且爬蟲第一波讀原始 HTML、第二波執行 JS,
     同一個 URL 會拿到兩種標題。 */
  var ownTitle = !!(document.title || "").trim();

  /* ---------- helpers shared with app.js ---------- */
  function t(obj) {
    if (obj == null) return "";
    if (typeof obj === "string") return obj;
    return obj[state.lang] || obj.en || obj.zh || "";
  }
  /* 第二個參數是要代入的欄位,例如 ui("sortBy", {label: "星數"}) →「依「星數」排序」。
     找不到 key 時退回英文那份再退回 key 本身 —— 回 undefined 會讓 aria-label
     變成字串 "undefined",那比缺字串更糟(讀屏會真的念出來)。 */
  function ui(key, vars) {
    var s = (I18N[state.lang] || {})[key];
    if (s == null) s = I18N.en[key];
    if (s == null) return key;
    if (vars) {
      for (var k in vars) {
        if (Object.prototype.hasOwnProperty.call(vars, k)) {
          s = s.replace("{" + k + "}", vars[k]);
        }
      }
    }
    return s;
  }
  function escapeHtml(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (m) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[m];
    });
  }
  function r(n) { return Math.round(n * 100) / 100; }

  /* 中文版鏡射在 zh-Hant/ 子目錄,頁與頁互為同目錄兄弟 ——
     所以 nav 連結在兩個語言裡長得一樣,天然留在當前語言。 */
  function pageHref(p) { return p.slug === "home" ? "index.html" : p.slug + ".html"; }
  /* 本頁在另一個語言的 URL(語言連結的目的地):root=en、zh-Hant/=zh */
  function altHref() {
    var file = location.pathname.split("/").pop() || "index.html";
    if (!/\.html$/.test(file)) file = "index.html";
    return state.lang === "zh" ? "../" + file : "zh-Hant/" + file;
  }
  function currentSlug() { return document.body.getAttribute("data-page") || "home"; }
  function currentPage() {
    var slug = currentSlug();
    for (var i = 0; i < PAGES.length; i++) if (PAGES[i].slug === slug) return PAGES[i];
    return PAGES[0] || null;
  }

  /* ---------- onLang callback registry(相容用) ----------
     語言固定於 URL 之後不再有「切換」事件,callback 永遠不會被呼叫;
     保留註冊介面只是讓既有 app.js 的 LDW.onLang(...) 不用改。 */
  var langSubscribers = [];
  function onLang(fn) { if (typeof fn === "function") langSubscribers.push(fn); }

  /* =======================================================================
     CHROME INJECTION — app bar, nav, footer, dialog around <main id="page">
     ===================================================================== */
  function injectChrome() {
    var main = document.getElementById("page");
    if (!main) return;

    /* skip link */
    var skip = document.createElement("a");
    skip.className = "skip-link";
    skip.href = "#page";
    skip.id = "skipLink";
    document.body.insertBefore(skip, document.body.firstChild);

    /* app bar */
    var appbar = document.createElement("header");
    appbar.className = "appbar";
    /* GitHub star button — only when SITE_META.repo is a filled "owner/name" */
    var repo = (META.repo || "").trim();
    /* 數字直接用快取的值畫進 markup。原本先寫死一個「—」再等 fetch 回來換掉,
       換頁時每次都會閃一下;而拿不到數字的時候那個「—」會一直留在畫面上,
       看起來像壞了 —— 星星鈕本身是連到 repo 的連結,沒有數字它照樣有用,
       所以拿不到就整個不顯示數字。 */
    var cached = repo ? starRead(repo) : null;
    var cachedN = (cached && typeof cached.n === "number") ? cached.n : null;
    var starHtml = (repo && repo.indexOf("{{") !== 0)
      ? '<a class="gh-star" id="ghStar" href="https://github.com/' + repo + '" target="_blank" rel="noopener" data-repo="' + repo + '">' +
          '<span class="material-symbols-rounded">star</span>' +
          '<span class="gh-star__label">Star</span>' +
          '<span class="gh-star__count" id="ghStarCount"' + (cachedN === null ? ' hidden' : '') + '>' +
            (cachedN === null ? '' : escapeHtml(starFmt(cachedN))) +
          '</span>' +
        '</a>'
      : '';
    /* 語言切換是真連結(每個語言一個 URL),指向本頁在另一語言的雙生檔 */
    var zh = state.lang === "zh";
    var langHtml =
      '<a class="icon-btn" id="langLink" href="' + escapeHtml(altHref()) + '"' +
        ' rel="alternate" hreflang="' + (zh ? "en" : "zh-Hant") + '"' +
        ' title="' + (zh ? "English" : "中文版") + '"' +
        /* aria-label 只用本頁的語言講(讀屏使用者聽的是本頁語言),
           看得見的 title / 文字才用目標語言的自稱(English / 中)——
           語言切換鈕用對方的自稱是慣例,不懂本頁語言的人也認得。 */
        ' aria-label="' + escapeHtml(ui("switchLang")) + '">' +
        '<span class="material-symbols-rounded">translate</span>' +
        '<span class="icon-btn__txt">' + (zh ? "EN" : "中") + '</span>' +
      '</a>';
    appbar.innerHTML =
      '<div class="appbar__inner">' +
        '<a class="brand" href="index.html">' +
          '<span class="material-symbols-rounded brand__logo">hub</span>' +
          '<span class="brand__name" id="brandName"></span>' +
        '</a>' +
        '<div class="appbar__actions">' +
          starHtml +
          langHtml +
          '<button class="icon-btn" id="themeToggle" type="button" title="' + escapeHtml(ui("theme")) + '" aria-label="' + escapeHtml(ui("theme")) + '">' +
            '<span class="material-symbols-rounded" id="themeIcon">dark_mode</span>' +
          '</button>' +
        '</div>' +
      '</div>';
    document.body.insertBefore(appbar, main);

    /* cross-page nav */
    var nav = document.createElement("nav");
    nav.className = "pagenav";
    nav.id = "pageNav";
    nav.innerHTML = '<div class="pagenav__inner" id="pageNavInner"></div>';
    document.body.insertBefore(nav, main);

    /* footer */
    var footer = document.createElement("footer");
    footer.className = "footer";
    footer.innerHTML = '<p id="footerText"></p>' +
      '<div class="footer__links">' +
        '<a class="icon-btn footer__link" href="https://www.peteraim.com" target="_blank" rel="noopener" title="peteraim.com" aria-label="' + escapeHtml(ui("homeLink")) + '"><span class="material-symbols-rounded">home</span></a>' +
        '<a class="icon-btn footer__link" href="https://www.linkedin.com/in/ai-med/" target="_blank" rel="noopener" title="LinkedIn" aria-label="' + escapeHtml(ui("linkedin")) + '"><svg viewBox="0 0 24 24" width="18" height="18" fill="currentColor" aria-hidden="true"><path d="M20.45 20.45h-3.55v-5.57c0-1.33-.02-3.04-1.85-3.04-1.85 0-2.13 1.45-2.13 2.94v5.67H9.36V9h3.41v1.56h.05c.47-.9 1.63-1.85 3.36-1.85 3.6 0 4.27 2.37 4.27 5.45v6.29zM5.34 7.43a2.06 2.06 0 1 1 0-4.12 2.06 2.06 0 0 1 0 4.12zM7.12 20.45H3.56V9h3.56v11.45zM22.22 0H1.77C.79 0 0 .77 0 1.72v20.56C0 23.23.79 24 1.77 24h20.45c.98 0 1.78-.77 1.78-1.72V1.72C24 .77 23.2 0 22.22 0z"/></svg></a>' +
      '</div>';
    main.parentNode.insertBefore(footer, main.nextSibling);

    /* shared detail dialog (used by card layouts) */
    var dialog = document.createElement("dialog");
    dialog.className = "dialog";
    dialog.id = "dialog";
    dialog.setAttribute("aria-labelledby", "dialogTitle");
    dialog.innerHTML =
      '<div class="dialog__bar">' +
        '<span class="dialog__spacer"></span>' +
        '<button class="icon-btn" id="dialogClose" type="button" aria-label="' + escapeHtml(ui("close")) + '">' +
          '<span class="material-symbols-rounded">close</span>' +
        '</button>' +
      '</div>' +
      '<div class="dialog__body" id="dialogBody"></div>';
    document.body.appendChild(dialog);

    /* dialog wiring (shared close behaviour; deep links handled by app.js) */
    document.getElementById("dialogClose").addEventListener("click", function () {
      if (dialog.open) dialog.close();
    });
    dialog.addEventListener("click", function (e) { if (e.target === dialog) dialog.close(); });

    /* 靜態備援語言連結是給無 JS 訪客與第一波爬蟲的;
       chrome 注入後 appbar 已有 #langLink,把備援藏起來避免重複。 */
    var fb = document.getElementById("langAlt");
    if (fb) (fb.closest("p") || fb).hidden = true;
  }

  function paintNav() {
    var inner = document.getElementById("pageNavInner");
    if (!inner) return;
    inner.innerHTML = "";
    var here = currentSlug();
    PAGES.forEach(function (p) {
      var a = document.createElement("a");
      a.className = "navpill" + (p.slug === here ? " navpill--active" : "");
      a.href = pageHref(p);
      if (p.slug === here) a.setAttribute("aria-current", "page");
      /* nav 用短名(navTitle),沒給才退回 title —— 首頁的 title 是完整站名,
         直接擺進 nav 會在 brand 正下方變成一條重複的長膠囊。 */
      a.innerHTML =
        '<span class="material-symbols-rounded" aria-hidden="true">' +
          escapeHtml(p.icon || "label") + "</span>" +
        "<span>" + escapeHtml(t(p.navTitle || p.title)) + "</span>";
      inner.appendChild(a);
    });
    /* keep the active pill in view within the scrolling nav */
    var active = inner.querySelector(".navpill--active");
    if (active && active.scrollIntoView) {
      active.scrollIntoView({ block: "nearest", inline: "center" });
    }
  }

  /* ---------- chrome text in the active language ---------- */
  function refreshChrome() {
    // <html lang> 由靜態檔自己宣告(語言即 URL),這裡不去動它。
    var page = currentPage();
    var siteTitle = t(META.title);
    var pageTitle = page ? t(page.title) : "";
    if (!ownTitle) {
      document.title = pageTitle ? pageTitle + " · " + siteTitle : siteTitle;
    }

    var brand = document.getElementById("brandName");
    if (brand) brand.textContent = siteTitle;
    var foot = document.getElementById("footerText");
    if (foot) foot.textContent = "© " + new Date().getFullYear() + " " + siteTitle;
    var skip = document.getElementById("skipLink");
    if (skip) skip.textContent = ui("skip");
    var nav = document.getElementById("pageNav");
    if (nav) nav.setAttribute("aria-label", ui("menu"));
    var dc = document.getElementById("dialogClose");
    if (dc) dc.setAttribute("aria-label", ui("close"));
    paintNav();
  }

  /* =======================================================================
     THEME + LANGUAGE
     ===================================================================== */
  function applyTheme() {
    document.documentElement.setAttribute("data-theme", state.theme);
    var icon = document.getElementById("themeIcon");
    if (icon) icon.textContent = state.theme === "dark" ? "light_mode" : "dark_mode";
    lsSet("theme", state.theme);
  }
  function wire() {
    document.getElementById("themeToggle").addEventListener("click", function () {
      state.theme = state.theme === "dark" ? "light" : "dark";
      applyTheme();
    });
  }

  /* =======================================================================
     PUBLIC TOOLKIT (app.js uses this)
     ===================================================================== */
  window.LDW = {
    ready: false,          // flipped true once the chrome (incl. #dialog) is injected
    state: state,
    t: t, ui: ui, escapeHtml: escapeHtml, r: r,
    lsGet: lsGet, lsSet: lsSet,
    pages: PAGES, meta: META,
    currentPage: currentPage, currentSlug: currentSlug, pageHref: pageHref,
    onLang: onLang,
    refreshChrome: refreshChrome,
    dialog: function () { return document.getElementById("dialog"); }
  };

  /* =======================================================================
     INIT
     ===================================================================== */
  /* ---------- GitHub star count (public API, no auth) ---------- */
  function showStarCount(n) {
    var c = document.getElementById("ghStarCount");
    if (!c) return;
    if (typeof n === "number") { c.textContent = starFmt(n); c.hidden = false; }
    else { c.textContent = ""; c.hidden = true; }
  }

  function loadStars() {
    var el = document.getElementById("ghStar");
    if (!el) return;
    var repo = el.dataset.repo;
    if (!repo || repo.indexOf("{{") === 0) return;       // unfilled → skip

    var c = starRead(repo);
    var age = c ? Date.now() - c.at : Infinity;
    /* 上一次失敗就用較短的退避,成功就用 TTL —— 兩個都沒過期就完全不發請求。
       這是省下額度的關鍵:換頁不該再打一次。
       判斷用 c.err 而不是「有沒有 n」,因為失敗時我們會把舊的 n 留著(見下面)。 */
    if (c && age < (c.err ? STAR_BACKOFF : STAR_TTL)) return;

    fetch("https://api.github.com/repos/" + repo,
          { headers: { Accept: "application/vnd.github+json" } })
      .then(function (res) {
        /* fetch 對 HTTP 錯誤碼**不會** reject —— 403(限流)、404 都會走到這裡
           而且 res.ok 是 false。不自己丟出來的話後面的 .catch 永遠不會執行,
           失敗就不會被記進快取,下一頁又會再打一次。 */
        if (!res.ok) throw new Error("HTTP " + res.status);
        return res.json();
      })
      .then(function (j) {
        if (!j || typeof j.stargazers_count !== "number") throw new Error("bad payload");
        starWrite(repo, { n: j.stargazers_count });
        showStarCount(j.stargazers_count);
      })
      .catch(function () {
        /* 離線、限流、repo 改名都到這裡。
           **舊的數字要留著** —— 只寫 {err:1} 會把之前抓到的數字覆蓋掉,
           那麼「快取過期 + 剛好這次限流」就等於永久失去數字,之後每 10 分鐘
           重試一次、每次都失敗、畫面一直空著。一個小時前的星數是完全堪用的。
           (JSON.stringify 會把 undefined 的 key 丟掉,所以沒有舊值時不會寫 n。) */
        starWrite(repo, { n: (c && typeof c.n === "number") ? c.n : undefined, err: 1 });
        if (!c || typeof c.n !== "number") showStarCount(null);
      });
  }

  function init() {
    injectChrome();
    loadStars();
    applyTheme();
    refreshChrome();
    wire();
    window.LDW.ready = true;
    document.dispatchEvent(new CustomEvent("ldw:shell-ready"));
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
